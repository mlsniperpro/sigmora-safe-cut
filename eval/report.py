"""Build ``eval/RESULTS.md`` (and its charts) from the committed runs in ``eval/results/`` only (WP7 step 6).

    uv run python eval/report.py           write eval/RESULTS.md and eval/results/charts/<split>.png
    uv run python eval/report.py --check   exit 1 if eval/RESULTS.md isn't exactly what the committed runs give

Every number in the tables links to the run that produced it. The newest run of each variant on each split is
reported; runs on synthetic recordings are reported in their own section, labelled synthetic. The service limits
section is generated from ``safecut/config.py``, so docs that quote a cap quote the code.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any, Literal, cast

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:  # run as a script (`python eval/report.py`): make the repo's packages importable
    sys.path.insert(0, str(ROOT))

from eval.variants import VARIANTS  # noqa: E402 -- after the sys.path line above, on purpose
from safecut.api.access import ESTIMATE_FLOOR_USD, ESTIMATE_PER_MINUTE_USD  # noqa: E402 -- as above
from safecut.config import Settings  # noqa: E402 -- after the sys.path line above, on purpose

RESULTS_DIR = ROOT / "eval" / "results"
OUT = ROOT / "eval" / "RESULTS.md"
NAMES = {
    "blur_all": "Blur every face (SAM 3.1 `face`, all hidden)",
    "egoblur": "EgoBlur Gen 2 on every frame",
    "detector_only": "Detector only (SAM 3.1 classes, no Muse Spark)",
    "muse_no_track": "Muse Spark keyframe boxes, no tracking",
    "full": "**Safe Cut (full)**",
    "no_audit": "Safe Cut without the audit pass",
}
DETECTOR_NAMES = {"yunet-face": "OpenCV YuNet face detector", "egoblur-gen1": "EgoBlur Gen 1"}
COLOURS = {
    "blur_all": "#9aa5b1",
    "egoblur": "#7b8794",
    "detector_only": "#52606d",
    "muse_no_track": "#c9a227",
    "full": "#2f6fed",
    "no_audit": "#89a7f5",
}


def load_runs(root: Path = RESULTS_DIR, splits: Path = ROOT / "eval" / "splits") -> list[dict[str, Any]]:
    runs: list[dict[str, Any]] = []
    for config_path in sorted(root.glob("*/config.json")):
        metrics_path = config_path.parent / "metrics.json"
        if not metrics_path.is_file():
            continue
        config = json.loads(config_path.read_text(encoding="utf-8"))
        if str(config.get("git_sha", "")).endswith("-dirty"):
            raise ValueError(f"{config_path.parent.name} ran on uncommitted code; only committed code backs a number")
        frozen = splits / "test.sha256"
        if config.get("split") == "test" and (
            not frozen.is_file() or frozen.read_text(encoding="utf-8").strip() != config.get("split_hash")
        ):
            raise ValueError(f"{config_path.parent.name} scored a test split that isn't the frozen one (test.sha256)")
        metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
        runs.append({"dir": config_path.parent.name, "config": config, "metrics": metrics})
    return runs


def pct(value: float | None, better: Literal["higher", "lower"]) -> str:
    """One decimal, always rounded in the unflattering direction (AGENTS rule 9: never round up), exactly as the
    landing page's table does (``web/src/components/landing/ResultsTable.tsx``): down for recall, up for
    exposure and over-blur."""
    if value is None:
        return "n/a"
    tenths = math.floor(value * 1000 + 1e-9) if better == "higher" else math.ceil(value * 1000 - 1e-9)
    return f"{tenths / 10:.1f}%"


def row_name(variant: str, run: dict[str, Any]) -> str:
    """The row's method name; the egoblur baseline is named after the detector that actually ran."""
    detector = run["config"].get("detail", {}).get("detector")
    if variant == "egoblur" and detector and detector != "egoblur-gen2":
        return f"{DETECTOR_NAMES.get(detector, detector)} on every frame (EgoBlur weights not installed)"
    return NAMES[variant]


def latest(runs: list[dict[str, Any]]) -> dict[tuple[str, bool], dict[str, dict[str, Any]]]:
    """(split, synthetic) → variant → the newest run."""
    table: dict[tuple[str, bool], dict[str, dict[str, Any]]] = {}
    for run in sorted(runs, key=lambda r: r["config"]["created_at"]):
        key = (run["config"]["split"], bool(run["config"].get("synthetic")))
        table.setdefault(key, {})[run["config"]["variant"]] = run
    return table


def render(runs: list[dict[str, Any]], settings: Settings | None = None) -> str:
    s = settings or Settings.model_construct()  # the shipped defaults, whatever this shell's SAFECUT_* say
    lines = [
        "# Results",
        "",
        "Generated by `eval/report.py` from the committed runs in `eval/results/` only; every figure links to its run.",
        "Recall: the share of should-hide entities covered (≥ 95 % of the box) on at least 95 % of their visible "
        "frames. Exposure: the share of should-hide entity-frames under 90 % covered. Leak bursts: runs of ≥ 3 "
        "consecutive exposed frames. Over-blur: the share of should-keep entities hidden (≥ 50 % covered) on more "
        "than 10 % of their frames. Metrics and their tests: `eval/metrics.py`, `tests/test_metrics.py`.",
        "",
    ]
    table = latest(runs)
    if not table:
        lines += ["No committed runs yet.", ""]
    for (split, synthetic), by_variant in sorted(table.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        title = f"## Split `{split}`" + (" (synthetic recordings)" if synthetic else "")
        lines += [title, ""]
        if synthetic:
            lines += [
                "> **Synthetic.** These runs replay responses generated from the clip's ground truth "
                "(`scripts/make_demo_job.py`), not model output. They show the pipeline and the metrics work "
                "end to end; they are not evidence of model quality.",
                "",
            ]
        lines += [
            "| Method | Recall | Exposure | Leak bursts | Over-blur | Needs-you items / min | Run |",
            "|---|---|---|---|---|---|---|",
        ]
        for variant in VARIANTS:
            run = by_variant.get(variant)
            if run is None:
                lines.append(f"| {NAMES[variant]} | not run | | | | | |")
                continue
            m, link = run["metrics"], f"[{run['dir']}](results/{run['dir']}/metrics.json)"
            name = row_name(variant, run)
            load = "n/a" if m["review_load_per_min"] is None else f"{m['review_load_per_min']:.2f}"
            lines.append(
                f"| {name} | {pct(m['entity_recall'], 'higher')} | {pct(m['exposure_rate'], 'lower')} | "
                f"{m['leak_bursts']} | {pct(m['over_blur'], 'lower')} | {load} | {link} |"
            )
        sizes = {
            (r["metrics"]["clips"], r["metrics"]["should_hide"], r["metrics"]["should_keep"], r["metrics"]["minutes"])
            for r in by_variant.values()
        }
        if len(sizes) > 1:
            raise ValueError(f"split {split}: the reported runs scored different clip sets {sorted(sizes)}")
        clips, hide, keep, minutes = sizes.pop()
        lines += [
            "",
            f"{clips} clip(s), {hide} should-hide and {keep} should-keep entities, {minutes:.2f} min of footage. "
            f"Chart: [charts/{split}{'-synthetic' if synthetic else ''}.png]"
            f"(results/charts/{split}{'-synthetic' if synthetic else ''}.png).",
            "",
        ]
        full = by_variant.get("full")
        if full is not None and full["config"].get("replay"):
            lines += ["Cost: none measured; replay runs make no API calls.", ""]
        elif full is not None:
            m = full["metrics"]
            lines += [
                f"Cost of the full run: ${m['cost_usd']:.2f} measured"
                + (f" (${m['cost_per_min']:.2f} per minute)" if m["cost_per_min"] is not None else "")
                + (f", plus ${m['cost_usd_estimated']:.2f} possibly billed" if m["cost_usd_estimated"] else "")
                + ".",
                "",
            ]
    lines += ["## Changes", "", *(f"- {change}" for change in CHANGES), ""]
    lines += [
        "## Service limits (from `safecut/config.py` defaults)",
        "",
        f"- Per-clip spend cap (`SAFECUT_JOB_USD_CAP`): ${s.job_usd_cap:.2f}.",
        f"- Daily cap for judge and public codes (`SAFECUT_DAILY_USD_CAP`): ${s.daily_usd_cap:.2f}, reset at "
        "00:00 UTC.",
        f"- Pilot codes: ${s.pilot_code_usd:.2f} each, ${s.pilot_pool_usd:.2f} in total; the recording code: up to "
        f"${s.recording_code_usd:.2f}.",
        f"- A job's worst-case estimate before it starts: the larger of ${ESTIMATE_FLOOR_USD:.2f} and "
        f"${ESTIMATE_PER_MINUTE_USD:.2f} per minute of footage.",
        f"- Clips: up to 60 s and 150 MB; jobs are deleted {s.job_ttl_hours:.0f} h after they're created (the "
        f"deletion sweep runs every {s.cleanup_interval_min} min, and a job past its time is refused on sight).",
        "",
    ]
    return "\n".join(lines)


README = ROOT / "README.md"
README_START, README_END = "<!-- results:start -->", "<!-- results:end -->"
#: What changed in the code behind the runs, newest first: one line each, written by hand, rendered as is.
CHANGES = (
    "2026-11-04: covers hide identity, not the shot: a person or child gets the face/head mosaic (the whole person "
    "only on the creator's Remove person); held covers stay at their object (half a second of back-fill, no motion "
    "sweep, bounded growth); a kept participant's face is never covered by another item (DESIGN §2.6, §2.7). The "
    "owner's call after the live street-interview review. Every dev run was re-run on that code; the synthetic dev "
    "clip's figures did not change.",
)


def readme_table(runs: list[dict[str, Any]]) -> str:
    """The README's results table: the newest run of each variant on the reported split. That is the test split
    once it has runs; until then the dev split, labelled synthetic when its recordings are."""
    table = latest(runs)
    key = next((k for k in sorted(table) if k[0] == "test"), None) or next(
        iter(sorted(table, key=lambda k: k[1])), None
    )
    if key is None:
        return "No committed runs yet."
    split, synthetic = key
    rows = [
        f"| Method ({split} split{', synthetic' if synthetic else ''}) | Recall | Exposure | Leak bursts | Over-blur |",
        "|---|---|---|---|---|",
    ]
    for variant in VARIANTS:
        run = table[key].get(variant)
        if run is not None:
            m = run["metrics"]
            rows.append(
                f"| {row_name(variant, run)} | {pct(m['entity_recall'], 'higher')} | "
                f"{pct(m['exposure_rate'], 'lower')} | {m['leak_bursts']} | {pct(m['over_blur'], 'lower')} |"
            )
    return "\n".join(rows)


def with_readme_table(readme: str, table: str) -> str:
    start, end = readme.index(README_START) + len(README_START), readme.index(README_END)
    return readme[:start] + "\n" + table + "\n" + readme[end:]


def charts(runs: list[dict[str, Any]], out: Path = RESULTS_DIR / "charts") -> list[Path]:
    import matplotlib  # noqa: PLC0415 -- charts only, and the backend must be set before pyplot loads

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt  # noqa: PLC0415 -- after the backend, as matplotlib requires

    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for (split, synthetic), by_variant in latest(runs).items():
        variants = [v for v in VARIANTS if v in by_variant]
        # matplotlib's own types are partial; the two handles are used only through calls documented for them.
        figure, axes = cast(tuple[Any, Any], plt.subplots(figsize=(8, 3.2), dpi=120))
        width = 0.38
        for offset, (key, label) in enumerate((("entity_recall", "Recall"), ("over_blur", "Over-blur"))):
            values = [by_variant[v]["metrics"][key] or 0.0 for v in variants]
            axes.bar(
                [i + (offset - 0.5) * width for i in range(len(variants))],
                values,
                width,
                label=label,
                color=[COLOURS[v] for v in variants],
                alpha=1.0 if offset == 0 else 0.45,
            )
        axes.set_xticks(range(len(variants)), [v.replace("_", " ") for v in variants], fontsize=8)
        axes.set_ylim(0, 1)
        axes.set_ylabel("share")
        axes.set_title(
            f"{split}{' (synthetic)' if synthetic else ''}: recall (solid) and over-blur (light)", fontsize=9
        )
        figure.tight_layout()
        path = out / f"{split}{'-synthetic' if synthetic else ''}.png"
        figure.savefig(path, metadata={"Software": None})
        plt.close(figure)
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="eval/report.py", description="Build eval/RESULTS.md from committed runs.")
    parser.add_argument("--check", action="store_true", help="fail if eval/RESULTS.md is out of date")
    args = parser.parse_args(argv)
    runs = load_runs(RESULTS_DIR)
    text = render(runs)
    readme = README.read_text(encoding="utf-8") if README.is_file() else ""
    readme_new = with_readme_table(readme, readme_table(runs)) if README_START in readme else readme
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text or readme_new != readme:
            stale = "eval/RESULTS.md" if current != text else "README.md's results table"
            print(f"{stale} is out of date: run `uv run python eval/report.py`", file=sys.stderr)
            return 1
        print("eval/RESULTS.md and the README's results table match the committed runs")
        return 0
    OUT.write_text(text, encoding="utf-8")
    README.write_text(readme_new, encoding="utf-8")
    charts(runs, RESULTS_DIR / "charts")
    print(f"wrote {OUT.name} and the README's results table from {len(runs)} run(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
